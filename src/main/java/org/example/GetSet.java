package org.example;

public class GetSet {

    private String name;
    private int age;
    private String course;

//    Getters
    public String getName() {
        return name;
    }
    public int  getAge() {
        return age;
    }
    public String getCourse() {
        return course;
    }

//    Setters
    public void setName(String name) {
        this.name = name;
    }
    public void setAge(int age) {
        this.age = age;
    }
    public void setCourse(String course) {
        this.course = course;
    }
}
